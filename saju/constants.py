# 왕상휴수사 계수 — 월령을 얻은 오행 1.0, 생을 받는 오행 0.8 …
WANGSANG = {"왕": 1.30, "상": 1.10, "휴": 0.85, "수": 0.70, "사": 0.55}


def season_factor(element: str, month_branch: str) -> float:
    """월지 기준 `element` 의 왕상휴수 계수."""
    ruling = MONTH_BRANCH_SEASON[month_branch]
    if element == ruling:
        return WANGSANG["왕"]
    if element == sheng_of(ruling):
        return WANGSANG["상"]
    if element == sheng_from(ruling):
        return WANGSANG["휴"]
    if element == ke_from(ruling):
        return WANGSANG["수"]
    return WANGSANG["사"]
