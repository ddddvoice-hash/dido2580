def sheng_of(element: str) -> str:
    """`element` 가 생(生)하는 오행."""
    return SHENG[element]


def sheng_from(element: str) -> str:
    """`element` 를 생(生)해 주는 오행."""
    return next(k for k, v in SHENG.items() if v == element)


def ke_of(element: str) -> str:
    """`element` 가 극(剋)하는 오행."""
    return KE[element]


def ke_from(element: str) -> str:
    """`element` 를 극(剋)하는 오행."""
    return next(k for k, v in KE.items() if v == element)


